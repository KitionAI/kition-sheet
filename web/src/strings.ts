type Translate = (key: string, params?: Record<string, string | number>) => string

/** Open-failure and other engine messages with a part that varies, and their catalog keys. */
const ERROR_PATTERNS: Array<[RegExp, string, string[]]> = [
  [/^command `([^`]+)` is not available right now: ([\s\S]*)$/, 'errorUnavailable', ['command', 'reason']],
  [/^invalid parameters for `([^`]+)`: ([\s\S]*)$/, 'errorInvalidParams', ['command', 'reason']],
  [/^internal error in `([^`]+)` \(the workbook was kept as it was\): ([\s\S]*)$/, 'errorInternal', ['command', 'reason']],
  [/^unknown command `([^`]+)`$/, 'errorUnknownCommand', ['command']],
  [/^'([\s\S]+)' is empty \(0 bytes\): there is no workbook in it\.$/, 'errorOpenEmpty', ['name']],
  [/^'([\s\S]+)' is password-protected\. /, 'errorOpenEncrypted', ['name']],
  [/^'([\s\S]+)' is not a spreadsheet: it is an Office binary file/, 'errorOpenLegacy', ['name']],
  [/^'([\s\S]+)' is an Excel 97-2003 \(\.xls\) workbook that can't be read \(([\s\S]*)\)\. /, 'errorOpenXls', ['name', 'reason']],
  [/^'([\s\S]+)' is damaged and can't be opened: ([\s\S]*)$/, 'errorOpenDamaged', ['name', 'reason']],
  [/^'([\s\S]+)' is (an? [^,]+), not a spreadsheet\.$/, 'errorOpenNotSheet', ['name', 'what']],
  [/^We can't import '([\s\S]+)': ([\s\S]*)$/, 'errorOpenImport', ['name', 'reason']],
  [/^We can't open '([\s\S]+)': ([\s\S]*)$/, 'errorOpenCant', ['name', 'reason']],
  [/^There's a problem with this formula: ([\s\S]*)$/, 'errorFormula', ['reason']],
  [/^We couldn't find what you were looking for: ([\s\S]*)$/, 'errorNotFound', ['what']],
]

/**
 * An engine message (a command refused, a workbook that does not open) in the editor's language:
 * the engine says it in English, the editor's catalogs translate it (`PHRASES` for whole
 * messages, the `error…` keys for those with a varying part, whose reason is translated too).
 */
export function localizeError(phrase: (text: string) => string, t: Translate, error: unknown, depth = 0): string {
  const text = error instanceof Error ? error.message : String(error)
  const whole = phrase(text)
  if (whole !== text || depth > 3) return whole
  // An agent's run names its step first.
  const step = /^step \d+ \(`[^`]+`\) failed: ([\s\S]*)$/.exec(text)
  if (step) return localizeError(phrase, t, step[1], depth + 1)
  for (const [pattern, key, names] of ERROR_PATTERNS) {
    const match = pattern.exec(text)
    if (!match) continue
    const params: Record<string, string> = {}
    names.forEach((name, index) => {
      const part = match[index + 1] ?? ''
      params[name] = name === 'reason' ? localizeError(phrase, t, part, depth + 1) : name === 'what' ? kindName(t, part) : part
    })
    const translated = t(key, params)
    return translated === key ? text : translated
  }
  return text
}

/** A kind of file named in an open failure (`a PDF document`), in the editor's language. */
function kindName(t: Translate, english: string) {
  const key = `errorKind:${english}`
  const translated = t(key)
  return translated === key ? english : translated
}
